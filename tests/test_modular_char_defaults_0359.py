"""Defaults for modular character creators, respecting explicit source flags."""
import configparser
from pathlib import Path
import tempfile
import unittest
import zipfile

from companion_tools.mod_packager.mod_packager_core import build_mod_zip
from forge_model_ini_link import read_linked_ini, save_linked_ini


class ModularCharacterDefaultsTest(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory(prefix="cfr_modular_defaults_")
        self.addCleanup(self.temp.cleanup)
        self.folder=Path(self.temp.name)
        self.model=self.folder/"model"
        self.model.mkdir()
        (self.model/"mad_racer.obj").write_text(
            "o Mad Racer\nv 0 0 0\nv 1 0 0\nv 0 1 0\nf 1 2 3\n",
            encoding="utf-8")

    def _pack(self,suffix):
        dest=self.folder/(suffix+".zip")
        build_mod_zip(title="Mad Katzz",
                      kind="Character",version="1.2",
                      source_folder=self.model,output=dest)
        with zipfile.ZipFile(dest) as archive:
            key=next(name for name in archive.namelist()
                     if name.endswith("/character.ini"))
            data=archive.read(key).decode("utf-8")
        config=configparser.ConfigParser(interpolation=None)
        config.read_string(data)
        return data,config

    def test_autogenerated_character_ini_modular_true_wheels_false(self):
        data,cfg=self._pack("auto")
        self.assertTrue(cfg.getboolean("character","modular_body"))
        self.assertFalse(cfg.has_option("character","has_wheels"))
        self.assertEqual(cfg.get("assets","asset_name"),"mad_racer")

    def test_supplied_missing_both_gets_defaults_only_inside_zip(self):
        p=self.model/"character.ini"
        old=("[character]\nname = MadKatzz\nenabled = true\n"
             "fallback_retail = pura\n\n"
             "[assets]\nasset_name = mad_racer\n")
        p.write_text(old,encoding="utf-8")
        data,cfg=self._pack("missing")
        self.assertTrue(cfg.getboolean("character","modular_body"))
        self.assertFalse(cfg.has_option("character","has_wheels"))
        self.assertEqual(p.read_text(encoding="utf-8"),old)
        self.assertIn("fallback_retail = pura",data)
        self.assertEqual(cfg.get("assets","asset_name"),"mad_racer")

    def test_existing_explicit_values_remain_intact(self):
        p=self.model/"character.ini"
        old=("[character]\nname=MadKatzz\nmodular_body = false\n"
             "has_wheels = true\n\n[assets]\nasset_name=mad_racer\n")
        p.write_text(old,encoding="utf-8")
        data,cfg=self._pack("authored")
        self.assertFalse(cfg.getboolean("character","modular_body"))
        self.assertFalse(cfg.has_option("character","has_wheels"))
        self.assertEqual(data.count("has_wheels"),0)
        self.assertEqual(data.count("modular_body"),1)

    def test_uppercase_section_keeps_explicit_settings(self):
        path=self.model/"character.ini"
        path.write_text(
            "[CHARACTER]\nname=Caps\nmodular_body = false\n"
            "has_wheels = true\n[assets]\nasset_name=mad_racer\n",
            encoding="utf-8")
        data,config=self._pack("caps")
        self.assertFalse(config.getboolean("CHARACTER","modular_body"))
        self.assertFalse(config.has_option("CHARACTER","has_wheels"))
        self.assertEqual(data.lower().count("modular_body"),1)
        self.assertEqual(data.lower().count("has_wheels"),0)

    def test_separate_vehicle_legacy_is_not_rewritten(self):
        p=self.model/"character.ini"
        p.write_text("[character]\nname=Mad\nseparate_vehicle = true\n",encoding="utf-8")
        data,cfg=self._pack("legacy")
        self.assertNotIn("modular_body",data)
        self.assertTrue(cfg.getboolean("character","separate_vehicle"))
        self.assertFalse(cfg.has_option("character","has_wheels"))

    def test_linked_ini_preserves_explicit_modular_false_on_offset_save(self):
        p=self.model/"character.ini"
        p.write_text("[character]\nname=Mad\nmodular_body = false\n"
                     "has_wheels = true\n[model]\nscale=1.0\n"
                     "offset_x=0.0\n",encoding="utf-8")
        link=read_linked_ini("character",p)
        self.assertEqual(link.fields["modular_body"],"false")
        self.assertNotIn("has_wheels",link.fields)
        edited=dict(link.fields,offset_x="1.5")
        backup=save_linked_ini(link,edited)
        self.assertTrue(backup.is_file())
        after=p.read_text()
        self.assertIn("modular_body = false",after)
        self.assertNotIn("has_wheels",after)
        self.assertIn("offset_x=1.5",after)


if __name__=="__main__":
    unittest.main()