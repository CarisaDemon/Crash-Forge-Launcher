"""Build an installable-looking music package without touching the game."""
from __future__ import annotations

from pathlib import Path
import re
import shutil

from cseq_format import parse_pack


_SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,62}$")


def validate_slug(slug: str) -> None:
    if not _SLUG_RE.fullmatch(slug):
        raise ValueError(
            "slug must be 1..63 chars using lowercase letters, digits, _ or -"
        )


def build_music_package(
    output_root: str | Path,
    slug: str,
    display_name: str,
    author: str,
    cseq_bytes: bytes,
    loop: bool = True,
    target: str = "",
    custom_samples: list[str | Path] | None = None,
    race_intro: bool = False,
) -> Path:
    """Create mods/music/<slug>/ style contents in an arbitrary output root.

    It deliberately does not copy anything into the live assets directory.
    """
    validate_slug(slug)
    parse_pack(cseq_bytes)  # Structural validation before writing.

    root = Path(output_root) / slug
    root.mkdir(parents=True, exist_ok=True)
    (root / "track.cseq").write_bytes(cseq_bytes)

    sample_list = [Path(x) for x in (custom_samples or [])]
    if sample_list:
        samples_dir = root / "samples"
        if samples_dir.exists():
            for old in samples_dir.glob("sample_*.wav"):
                old.unlink()
        samples_dir.mkdir(parents=True, exist_ok=True)
        for slot, source in enumerate(sample_list):
            if not source.is_file():
                raise ValueError(f"custom sample missing: {source}")
            shutil.copy2(source, samples_dir / f"sample_{slot:03d}.wav")

    lines = [
        "[music]",
        f"slug = {slug}",
        f"name = {display_name}",
        f"author = {author}",
        "source = cseq",
        "file = track.cseq",
        f"loop = {'true' if loop else 'false'}",
        "enabled = true",
        f"custom_samples = {len(sample_list)}",
        f"race_intro = {'true' if race_intro else 'false'}",
    ]
    if target:
        lines.append(f"target = {target}")
    lines += [
        "",
        "# Generated by Crash Forge MIDI/CSEQ Tool.",
        "# Live CSEQ packages belong under assets/mods/music/<slug>/.",
        "# The loader keeps KART.HWL and all retail game files untouched.",
        "",
    ]
    (root / "music.ini").write_text("\n".join(lines), encoding="utf-8")
    return root
